const TYPE_LABELS = {
  quiz: 'MCQ', true_false: 'T/F', multiple_select_quiz: 'Multi',
  pin_it: 'Pin', jumble: 'Jumble', slider: 'Slider', open_ended: 'Open'
};
const PROVIDER_LABELS = { openai: 'OpenAI', gemini: 'Google AI Studio', openrouter: 'OpenRouter' };
const SEND_FAILED_MESSAGES = {
  pin_it: 'Pin stays on the page · check it and submit manually if needed',
  slider: 'Slider value stays on the page · check it and submit manually if needed'
};

export function createLiveSessionQuestionView({
  liveStatus,
  liveDetail,
  questionReadiness,
  answerHandoff,
  liveEmpty,
  liveQuestion,
  questionText,
  answerText,
  retryAnswerBtn,
  getHasCurrentQuestion,
  setHasCurrentQuestion
}) {
  let liveStatusState = 'idle';
  let readinessRetryToken = null;
  let readinessRetryAvailable = false;
  let readinessRetryPending = false;
  let choiceReadinessActive = false;

  function syncRetryButton() {
    if (!retryAnswerBtn) return;
    retryAnswerBtn.disabled = !canRetry();
  }

  function canRetry() {
    const canRetryReadiness = readinessRetryAvailable && Boolean(readinessRetryToken) &&
      !readinessRetryPending && liveStatusState !== 'processing';
    const canRetryNormally = !choiceReadinessActive && liveStatusState !== 'processing' && liveStatusState !== 'waiting_for_choices';
    return getHasCurrentQuestion() && !readinessRetryPending && (canRetryReadiness || canRetryNormally);
  }

  function showHandoff(handoff) {
    if (!answerHandoff || !handoff?.stage) return;
    const provider = PROVIDER_LABELS[handoff.provider] || 'AI provider';
    const nextProvider = PROVIDER_LABELS[handoff.nextProvider] || 'AI provider';
    const model = String(handoff.model || '').slice(0, 100);
    const nextModel = String(handoff.nextModel || '').slice(0, 100);
    const status = {
      attempt: `Contacting ${provider}${model ? ` · ${model}` : ''}${handoff.attempt ? ` · attempt ${handoff.attempt}` : ''}`,
      success: `Answer generated by ${provider}${model ? ` · ${model}` : ''}`,
      failed: handoff.nextProvider
        ? `${provider} failed${handoff.httpStatus ? ` · HTTP ${handoff.httpStatus}` : ''} → trying ${nextProvider}${nextModel ? ` · ${nextModel}` : ''}`
        : `${provider} request failed${handoff.httpStatus ? ` · HTTP ${handoff.httpStatus}` : ''}`,
      matching: 'AI answer ready · checking it against the visible choices',
      matched: 'Answer matched · preparing the game action',
      highlighted: 'Answer matched · highlighted on the page',
      suggested: 'Answer suggestion ready · review before submitting',
      manual_review: 'Answer match is uncertain · review before submitting',
      sending: 'Sending answer to the game…',
      sent: 'Answer action was sent · game acceptance is unconfirmed',
      send_failed: SEND_FAILED_MESSAGES[handoff.questionType] || 'Game connection is not ready · the answer remains available on the page'
    }[handoff.stage];
    if (!status) return;
    answerHandoff.textContent = status;
    answerHandoff.dataset.stage = handoff.stage === 'failed' ? 'failed' : handoff.stage;
    answerHandoff.classList.remove('hidden');
  }

  function clearAnswerHandoff() {
    if (!answerHandoff) return;
    answerHandoff.textContent = '';
    answerHandoff.classList.add('hidden');
    answerHandoff.removeAttribute('data-stage');
  }

  function showReadiness(readiness) {
    if (!readiness?.choicesRequired) {
      choiceReadinessActive = false;
      readinessRetryToken = null;
      readinessRetryAvailable = false;
      readinessRetryPending = false;
      if (questionReadiness) {
        questionReadiness.textContent = '';
        questionReadiness.classList.add('hidden');
        questionReadiness.removeAttribute('data-ready');
      }
      syncRetryButton();
      return;
    }
    choiceReadinessActive = readiness.choicesReady !== true;
    readinessRetryAvailable = readiness.recoveryExpired === true && typeof readiness.retryToken === 'string';
    readinessRetryToken = readinessRetryAvailable ? readiness.retryToken : null;
    readinessRetryPending = false;
    syncRetryButton();
    if (!questionReadiness) return;
    const expected = Math.max(2, Number(readiness.expectedChoiceCount) || 2);
    const received = Math.max(0, Number(readiness.dataChoiceCount) || 0);
    const visible = Math.max(0, Number(readiness.visibleChoiceCount) || 0);
    if (readiness.choicesReady) {
      questionReadiness.textContent = `Choice set ready · ${visible || received} answer choices`;
      questionReadiness.dataset.ready = 'true';
    } else if (visible > 0) {
      questionReadiness.textContent = `Page choices · ${visible} of ${expected} required · waiting before AI request`;
      questionReadiness.dataset.ready = 'false';
    } else if (received > 0) {
      questionReadiness.textContent = `${received} choice${received === 1 ? '' : 's'} received · checking the page for at least ${expected}`;
      questionReadiness.dataset.ready = 'false';
    } else {
      questionReadiness.textContent = `No answer choices received · checking the page for at least ${expected}`;
      questionReadiness.dataset.ready = 'false';
    }
    if (readinessRetryAvailable) {
      questionReadiness.textContent = `Choice check expired · found ${visible} of at least ${expected}. Try again to check the page; no AI request has been sent.`;
      questionReadiness.dataset.ready = 'false';
    }
    questionReadiness.classList.remove('hidden');
  }

  function setLiveStatus(state, label, detail = '') {
    liveStatusState = state;
    if (state === 'error' || state === 'processing') readinessRetryPending = false;
    if (liveStatus) {
      liveStatus.textContent = label;
      liveStatus.className = `live-status state-${state}`;
    }
    if (liveDetail) liveDetail.textContent = detail;
    syncRetryButton();
  }

  function showQuestion(title, type, readiness) {
    if (!title) return;
    setHasCurrentQuestion(true);
    liveEmpty?.classList.add('hidden');
    liveQuestion?.classList.remove('hidden');
    const badge = type && TYPE_LABELS[type] ? `${TYPE_LABELS[type]} · ` : '';
    if (questionText) {
      questionText.textContent = badge + title;
      questionText.classList.add('active');
    }
    showReadiness(readiness);
    syncRetryButton();
  }

  function showAnswer(answer) {
    if (!answer) return;
    setHasCurrentQuestion(true);
    liveEmpty?.classList.add('hidden');
    liveQuestion?.classList.remove('hidden');
    if (answerText) {
      answerText.textContent = answer;
      answerText.classList.remove('thinking');
      answerText.classList.add('active');
    }
    setLiveStatus('answered', 'Answer ready', 'Review the suggestion before submitting.');
  }

  function setThinking() {
    if (answerText) {
      answerText.textContent = 'Working on it…';
      answerText.classList.add('thinking');
      answerText.classList.remove('active');
    }
    setLiveStatus('processing', 'Finding an answer…', 'The selected provider and any enabled fallback providers may receive this question.');
  }

  function setWaitingForChoices(readiness) {
    showReadiness(readiness);
    if (answerText) {
      answerText.textContent = 'Waiting for the game to show the answer options…';
      answerText.classList.remove('thinking', 'active');
    }
    const expected = Math.max(2, Number(readiness?.expectedChoiceCount) || 2);
    const received = Math.max(0, Number(readiness?.dataChoiceCount) || 0);
    const visible = Math.max(0, Number(readiness?.visibleChoiceCount) || 0);
    const detail = visible
      ? `The page shows ${visible} of at least ${expected} readable choices. No AI request has been sent.`
      : received
        ? `${received} choice${received === 1 ? '' : 's'} arrived from the game. Checking the page for at least ${expected}; no AI request has been sent.`
        : `No choices arrived yet. Checking the page for at least ${expected}; no AI request has been sent.`;
    const expired = readiness?.recoveryExpired === true;
    setLiveStatus('waiting_for_choices', expired ? 'Answer options not ready' : 'Waiting for answer options', detail);
  }

  function beginReadinessRetry() {
    if (!readinessRetryAvailable || !readinessRetryToken) return null;
    readinessRetryPending = true;
    liveStatusState = 'waiting_for_choices';
    if (answerText) {
      answerText.textContent = 'Checking the game page for answer options again…';
      answerText.classList.remove('thinking', 'active');
    }
    if (liveStatus) {
      liveStatus.textContent = 'Checking answer options';
      liveStatus.className = 'live-status state-waiting_for_choices';
    }
    if (liveDetail) liveDetail.textContent = 'Rechecking the current question. No AI request will be sent until the complete choices appear.';
    syncRetryButton();
    return readinessRetryToken;
  }

  function clearSelectedQuestion() {
    setHasCurrentQuestion(false);
    liveStatusState = 'idle';
    choiceReadinessActive = false;
    readinessRetryToken = null;
    readinessRetryAvailable = false;
    readinessRetryPending = false;
    syncRetryButton();
    liveEmpty?.classList.remove('hidden');
    liveQuestion?.classList.add('hidden');
    if (questionReadiness) {
      questionReadiness.textContent = '';
      questionReadiness.classList.add('hidden');
      questionReadiness.removeAttribute('data-ready');
    }
    clearAnswerHandoff();
    if (questionText) questionText.textContent = '';
    if (answerText) {
      answerText.textContent = 'Waiting for a response';
      answerText.classList.remove('thinking', 'active');
    }
  }

  return {
    clearAnswerHandoff,
    clearSelectedQuestion,
    beginReadinessRetry,
    canRetry,
    getReadinessRetryToken: () => readinessRetryAvailable ? readinessRetryToken : null,
    setLiveStatus,
    setThinking,
    setWaitingForChoices,
    showAnswer,
    showHandoff,
    showQuestion,
    showReadiness
  };
}
