(function initRuntimeMessageHandler(global) {
  'use strict';

  function createRuntimeMessageHandler(dependencies) {
    const {
      state,
      isPluginEnabled = () => true,
      questionScopedActions,
      nonRetryableDiagnostics,
      questionHash,
      matching,
      updateStatus,
      broadcastToPopup,
      answerFeedbackUi,
      answerActions,
      sendQuestionToBackend,
      recordDiagnostic,
      log,
      warn,
      showErrorToast
    } = dependencies;

    function handleMessage(request, _sender, sendResponse) {
      if (!isPluginEnabled() && request.action !== 'ping' && request.action !== 'getQuestion') {
        sendResponse({ success: false, disabled: true });
        return false;
      }

      if (request.requestId && questionScopedActions.has(request.action) &&
          (!state.currentQuestion || request.requestId !== questionHash(state.currentQuestion) || request.requestId !== state.activeRequestId)) {
        sendResponse({ success: false, stale: true });
        return false;
      }

      switch (request.action) {
        case 'ping':
          sendResponse({ connected: true });
          break;

        case 'answerProgress': {
          const handoff = {
            stage: request.event,
            provider: request.provider,
            model: request.model,
            attempt: request.attempt,
            httpStatus: request.httpStatus,
            nextProvider: request.nextProvider,
            nextModel: request.nextModel
          };
          const providerName = ({ openai: 'OpenAI', gemini: 'Google AI Studio', openrouter: 'OpenRouter' })[request.provider] || 'AI provider';
          const nextName = ({ openai: 'OpenAI', gemini: 'Google AI Studio', openrouter: 'OpenRouter' })[request.nextProvider] || 'AI provider';
          if (request.event === 'attempt') {
            updateStatus(`Contacting ${providerName}…`, request.model || 'Checking configured model', handoff);
          } else if (request.event === 'success') {
            updateStatus(`Answer generated by ${providerName}`, request.model || '', handoff);
          } else if (request.event === 'failed' && request.nextProvider) {
            const reason = request.httpStatus ? `HTTP ${request.httpStatus}` : 'request error';
            updateStatus(`${providerName} failed · trying ${nextName}`, `${reason} · ${request.nextModel || ''}`, handoff);
          } else if (request.event === 'failed') {
            updateStatus(`${providerName} request failed`, request.httpStatus ? `HTTP ${request.httpStatus}` : 'No alternate provider was available.', handoff);
          }
          sendResponse({ success: true });
          break;
        }

        case 'highlightAnswer': {
          state.hasRetried = false;
          state.pendingRetryHash = null;
          if (state.currentQuestion) state.lastSentHash = questionHash(state.currentQuestion);

          const answersFromAI = request.answers || [];
          const currentChoices = state.currentQuestion?.choices || [];
          if (currentChoices.length > 0 && answersFromAI.length > 0) {
            const validAnswerSet = matching.validateAnswerSet(currentChoices, answersFromAI, !!request.isMultiSelect);
            if (!validAnswerSet) {
              warn('A stale or ambiguous answer was rejected.');
              recordDiagnostic('ANSWER_NO_MATCH', { stage: 'matching' });
              updateStatus('Error: answer did not match current choices', 'Try again or check the provider response.');
              state.lastSentHash = null;
              sendResponse({ success: false });
              break;
            }
          }

          state.currentAnswer = answersFromAI.join(', ');
          const shortAnswer = state.currentAnswer.length > 60 ? state.currentAnswer.slice(0, 57) + '...' : state.currentAnswer;
          const timing = request.elapsed ? ` (${request.elapsed})` : '';
          updateStatus(`Answer received ✅${timing}`, shortAnswer, { stage: 'matching' });
          broadcastToPopup('updateAnswer', { answer: state.currentAnswer });
          answerFeedbackUi.cleanupOverlays();
          log(`Answer received (${answersFromAI.length} choice${answersFromAI.length === 1 ? '' : 's'})`);
          answerActions.highlightAnswers(answersFromAI, request.isMultiSelect, request.options);
          sendResponse({ success: true });
          break;
        }

        case 'getQuestion':
          if (!state.currentQuestion) return false;
          sendResponse({
            question: state.currentQuestion,
            answer: state.currentAnswer,
            state: state.questionState,
            error: state.questionError,
            readiness: state.currentQuestionReadiness
          });
          break;

        case 'showError': {
          const message = typeof request.message === 'string' ? request.message.slice(0, 160) : 'Question processing failed';
          const suggestion = typeof request.suggestion === 'string' ? request.suggestion.slice(0, 240) : 'Open Debug details for recovery guidance.';
          updateStatus(`Error ❌ · ${message}`, suggestion);
          broadcastToPopup('updateStatus', { status: `Could not answer · ${message}`, detail: suggestion, state: 'error' });
          showErrorToast(`${message}. ${suggestion}`);
          sendResponse({ success: true });
          if (state.currentQuestion && !state.hasRetried && !nonRetryableDiagnostics.has(request.diagnosticCode)) {
            state.hasRetried = true;
            state.pendingRetryHash = questionHash(state.currentQuestion);
            state.lastSentHash = state.pendingRetryHash;
            updateStatus('Retrying in 2s...');
            setTimeout(() => {
              if (state.currentQuestion && state.pendingRetryHash === questionHash(state.currentQuestion)) {
                sendQuestionToBackend(state.currentQuestion);
              }
              state.pendingRetryHash = null;
            }, 2000);
          } else {
            state.lastSentHash = null;
            state.lastPreparedHash = null;
          }
          break;
        }

        case 'manualAnswer':
          if (!state.currentQuestion) return false;
          if (state.questionState === 'waiting_for_choices') {
            const readiness = state.currentQuestionReadiness;
            const retryToken = readiness?.recoveryExpired === true ? readiness.retryToken : null;
            if (!retryToken || request.readinessRetryToken !== retryToken) {
              sendResponse({ success: false, message: 'Waiting for the current question’s answer choices.' });
              break;
            }
            state.pendingRetryHash = null;
            state.hasRetried = false;
            state.lastSentHash = null;
            global.dispatchEvent(new global.CustomEvent('kahootQuestionParsed', {
              detail: {
                ...state.currentQuestion,
                choices: Array.isArray(state.currentQuestion.choices) ? [...state.currentQuestion.choices] : []
              }
            }));
            sendResponse({ success: true, readinessRetry: true });
            break;
          }
          state.pendingRetryHash = null;
          state.hasRetried = false;
          state.lastSentHash = null;
          updateStatus('Manual retry...', state.currentQuestion.title);
          sendResponse({ success: sendQuestionToBackend(state.currentQuestion) });
          break;

        case 'getPinImageUrl':
          sendResponse({ imageUrl: answerActions.extractPinImageUrl() });
          break;

        case 'getQuestionImageUrl':
          sendResponse({ imageUrl: answerActions.extractQuestionImageUrl() });
          break;

        case 'placePin':
          completeDirectAnswer({
            label: 'Pin answer',
            answer: `📍 ${request.coords.x.toFixed(1)}%, ${request.coords.y.toFixed(1)}%`,
            elapsed: request.elapsed,
            applyAnswer: () => answerActions.placePinOnSvg(request.coords, request.options)
          });
          sendResponse({ success: true });
          break;

        case 'reorderJumble':
          completeDirectAnswer({
            label: 'Jumble answer',
            answer: `🧩 ${request.answerWord}`,
            elapsed: request.elapsed,
            applyAnswer: () => answerActions.solveJumbleFromDOM(request.answerWord, request.options)
          });
          sendResponse({ success: true });
          break;

        case 'setSlider':
          completeDirectAnswer({
            label: 'Slider answer',
            answer: `🎚️ ${request.value}`,
            elapsed: request.elapsed,
            applyAnswer: () => answerActions.solveSliderFromDOM(request.value, request.options)
          });
          sendResponse({ success: true });
          break;

        case 'typeOpenEnded':
          completeDirectAnswer({
            label: 'Open-ended answer',
            answer: `✏️ ${request.answer}`,
            elapsed: request.elapsed,
            applyAnswer: () => answerActions.dispatchOpenEndedAnswer(request.answer, request.options)
          });
          sendResponse({ success: true });
          break;
      }
      return true;
    }

    function completeDirectAnswer({ label, answer, elapsed, applyAnswer }) {
      state.hasRetried = false;
      state.pendingRetryHash = null;
      if (state.currentQuestion) state.lastSentHash = questionHash(state.currentQuestion);
      state.currentAnswer = answer;
      updateStatus(`${label} ✅${elapsed ? ` (${elapsed})` : ''}`, answer);
      broadcastToPopup('updateAnswer', { answer });
      applyAnswer();
    }

    return {
      register() {
        chrome.runtime.onMessage.addListener(handleMessage);
      }
    };
  }

  global.UwUKahootAIRuntimeMessageHandler = { create: createRuntimeMessageHandler };
})(globalThis);
